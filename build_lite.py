#!/usr/bin/env python3
"""Build docs/index.html (Lite) from index.html (single source of truth).

The Lite build is the same single-file app with a smaller default source
set, so there is no second copy of the 1,000-line frontend to maintain.
Run `python build_lite.py` after editing index.html; `--check` verifies the
committed output is current (used by CI).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'index.html'
TARGET = ROOT / 'docs' / 'index.html'
MARKER = '<!-- Generated by build_lite.py from index.html — do not edit directly. -->'

REPLACEMENTS = (
    ('<title>EchoWave Music</title>',
     '<title>EchoWave Lite</title>'),
    ('<span>Music Platform</span>',
     '<span>Lite</span>'),
    ('    <div class="proxy-status" id="proxy-status">⚠ Proxy offline — Kuwo/Kugou/Migu limited to preview'
     '<br><span style="opacity:0.7">Run <code>python server.py</code> · needs '
     '<code>pip install -r requirements.txt</code></span></div>\n',
     ''),
    ('Discover music from<br/>NetEase · QQ · Kuwo · Kugou · Migu',
     'Discover music from<br/>NetEase · QQ Music'),
    ('sources:{netease:true,qq:true,kuwo:true,kugou:false,migu:false}',
     'sources:{netease:true,qq:true,kuwo:false,kugou:false,migu:false}'),
)


def render(source_text):
    """Apply the Lite transformations, failing loudly if the source drifts."""
    text = source_text
    for old, new in REPLACEMENTS:
        if old not in text:
            raise SystemExit(
                'build_lite: expected fragment not found in index.html:\n  %r' % old[:120]
            )
        text = text.replace(old, new, 1)
    if MARKER not in text:
        text = text.replace(
            '<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + MARKER + '\n', 1
        )
    return text


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    check = '--check' in args

    text = render(SOURCE.read_text(encoding='utf-8'))

    if check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        if current != text:
            print('docs/index.html is out of date — run: python build_lite.py')
            return 1
        print('docs/index.html is up to date')
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with TARGET.open('w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)
    print('Wrote %s (%d bytes)' % (TARGET.relative_to(ROOT), len(text)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
